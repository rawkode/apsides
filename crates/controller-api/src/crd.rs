use std::{fs, path::Path};

use k8s_openapi::apiextensions_apiserver::pkg::apis::apiextensions::v1::CustomResourceDefinition;
use kube::CustomResourceExt;
use serde_json::Value;
use thiserror::Error;

use crate::{AutomationRun, OxideLoopState, WebApplication};

const OUTPUT_PATH: &str = "deploy/crds/oxideloop-crds.yaml";

#[derive(Debug, Error)]
pub enum CrdError {
    #[error("failed to serialize generated CRDs: {0}")]
    Serialize(#[from] serde_yaml::Error),
    #[error("failed to write generated CRDs: {0}")]
    Write(#[from] std::io::Error),
    #[error("generated CRDs are stale at {path}")]
    Drift { path: String },
    #[error("generated CRD {name} is not strict and structural: {reason}")]
    NonStructural { name: String, reason: &'static str },
    #[error("generated CRD contract is incomplete: {0}")]
    Contract(&'static str),
    #[error("failed to convert generated CRD to a structural document: {0}")]
    Json(String),
}

/// Renders all controller CRDs in a deterministic order.
///
/// # Errors
///
/// Returns an error when a generated CRD lacks its structural requirements or
/// cannot be serialized.
pub fn crd_documents() -> Result<String, CrdError> {
    let mut crds = vec![
        WebApplication::crd(),
        OxideLoopState::crd(),
        AutomationRun::crd(),
    ];
    for crd in &mut crds {
        // This is intentional and checked below. It prevents legacy global
        // unknown-field preservation and keeps all schemas structural.
        crd.spec.preserve_unknown_fields = Some(false);
        verify_structural(crd)?;
    }
    crds.sort_by(|left, right| left.metadata.name.cmp(&right.metadata.name));
    let mut output = String::from(
        "# Generated by `cargo run -p oxideloop-controller-api --bin generate-controller-api`. Do not edit.\n",
    );
    for (index, crd) in crds.iter().enumerate() {
        if index > 0 {
            output.push_str("---\n");
        }
        let document =
            serde_json::to_value(crd).map_err(|error| CrdError::Json(error.to_string()))?;
        verify_generated_schema_contracts(&document)?;
        output.push_str(&serde_yaml::to_string(&document)?);
    }
    Ok(output)
}

/// Checks generated CRD structure that can be verified without an API server.
///
/// This deliberately does not claim to execute Kubernetes' CEL admission
/// evaluator; a live-server admission test remains the missing verification
/// boundary. It proves the generated YAML is typed and prunable, retains
/// bounded replay bytes, and contains the required immutable-spec CEL.
fn verify_generated_schema_contracts(document: &Value) -> Result<(), CrdError> {
    verify_prunable_schema(document)?;
    let kind = document
        .pointer("/spec/names/kind")
        .and_then(Value::as_str)
        .ok_or(CrdError::Contract("CRD kind is missing"))?;
    match kind {
        "AutomationRun" => {
            let replay = document.pointer(
                "/spec/versions/0/schema/openAPIV3Schema/properties/spec/properties/actionInputV0/maxLength",
            );
            if replay.and_then(Value::as_u64) != Some(524_288) {
                return Err(CrdError::Contract(
                    "AutomationRun actionInputV0 must retain its 512 KiB schema bound",
                ));
            }
            require_cel(
                document,
                "self.spec == oldSelf.spec",
                "AutomationRun spec immutability CEL is missing",
            )?;
        }
        "OxideLoopState" => {
            require_cel(
                document,
                "self.spec.stateVersion == 1",
                "OxideLoopState version CEL is missing",
            )?;
            require_cel(
                document,
                "self.spec.root == oldSelf.spec.root",
                "OxideLoopState root immutability CEL is missing",
            )?;
        }
        "WebApplication" => {}
        _ => return Err(CrdError::Contract("unexpected generated CRD kind")),
    }
    Ok(())
}

fn verify_prunable_schema(value: &Value) -> Result<(), CrdError> {
    match value {
        Value::Array(values) => {
            for value in values {
                verify_prunable_schema(value)?;
            }
        }
        Value::Object(object) => {
            if object.get("x-kubernetes-preserve-unknown-fields") == Some(&Value::Bool(true)) {
                return Err(CrdError::Contract(
                    "schema must not preserve unknown fields",
                ));
            }
            if object.get("type").and_then(Value::as_str) == Some("object")
                && !object.contains_key("properties")
            {
                return Err(CrdError::Contract(
                    "every schema object must declare typed properties",
                ));
            }
            for value in object.values() {
                verify_prunable_schema(value)?;
            }
        }
        _ => {}
    }
    Ok(())
}

fn require_cel(document: &Value, rule: &str, missing: &'static str) -> Result<(), CrdError> {
    let Some(validations) = document
        .pointer("/spec/versions/0/schema/openAPIV3Schema/x-kubernetes-validations")
        .and_then(Value::as_array)
    else {
        return Err(CrdError::Contract(missing));
    };
    if validations
        .iter()
        .any(|validation| validation.get("rule").and_then(Value::as_str) == Some(rule))
    {
        Ok(())
    } else {
        Err(CrdError::Contract(missing))
    }
}

/// Writes generated CRDs, or verifies that the checked-in artifact is current.
///
/// # Errors
///
/// Returns an error when rendering fails, output cannot be written, or
/// `check` finds a stale checked-in artifact.
pub fn write_or_check_crds(root: &Path, check: bool) -> Result<(), CrdError> {
    let document = crd_documents()?;
    let output_path = root.join(OUTPUT_PATH);
    if check {
        let actual = fs::read_to_string(&output_path).unwrap_or_default();
        if actual == document {
            return Ok(());
        }
        return Err(CrdError::Drift {
            path: output_path.display().to_string(),
        });
    }
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(output_path, document)?;
    Ok(())
}

fn verify_structural(crd: &CustomResourceDefinition) -> Result<(), CrdError> {
    let name = crd
        .metadata
        .name
        .clone()
        .unwrap_or_else(|| "<unnamed>".into());
    if crd.spec.preserve_unknown_fields != Some(false) {
        return Err(CrdError::NonStructural {
            name,
            reason: "spec.preserveUnknownFields is not explicitly false",
        });
    }
    for version in &crd.spec.versions {
        if version
            .subresources
            .as_ref()
            .and_then(|subresources| subresources.status.as_ref())
            .is_none()
        {
            return Err(CrdError::NonStructural {
                name,
                reason: "status subresource is missing",
            });
        }
        if version.schema.is_none() {
            return Err(CrdError::NonStructural {
                name,
                reason: "openAPIV3Schema is missing",
            });
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::{fs, path::PathBuf};

    use super::*;

    #[test]
    fn checked_in_crds_are_current_and_client_side_prunable() {
        let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
        write_or_check_crds(&root, true).unwrap();
        let document = fs::read_to_string(root.join(OUTPUT_PATH)).unwrap();
        assert!(document.contains("preserveUnknownFields: false"));
        assert_eq!(document.matches("subresources:").count(), 3);
        assert!(!document.contains("x-kubernetes-preserve-unknown-fields: true"));
        assert!(!document.contains("additionalProperties:"));
        assert!(document.contains("rule: self.spec == oldSelf.spec"));
        // This is deliberately a generated-schema inspection only. It cannot
        // exercise the API server's structural-schema or CEL admission path.
    }
}
