import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";
import { parseAllDocuments } from "yaml";

const HEADER = "// Generated by aps crds fetch. Do not edit.\n";
const MAX_BYTES = 8 * 1024 * 1024;
type ObjectValue = Record<string, unknown>;
function object(value: unknown): value is ObjectValue {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function schemaData(value: unknown, depth = 0): void {
  if (depth > 100) throw new Error("CRD schema is too deeply nested");
  if (Array.isArray(value)) {
    for (const item of value) schemaData(item, depth + 1);
  } else if (object(value)) {
    for (const [key, child] of Object.entries(value)) {
      if (key === "tsType" || key === "tsEnumNames") throw new Error("CRD cannot supply TypeScript code");
      if (key === "$ref" && (typeof child !== "string" || !child.startsWith("#/"))) throw new Error("external schema references are unsupported");
      schemaData(child, depth + 1);
    }
  }
}

export async function generateCrdTypes(text: string, kind: string, version?: string): Promise<string> {
  if (Buffer.byteLength(text) > MAX_BYTES || !/^[A-Z][A-Za-z0-9]*$/.test(kind)) {
    throw new Error("invalid CRD input or kind");
  }
  const documents = parseAllDocuments(text);
  if (documents.some(document => document.errors.length !== 0)) throw new Error("invalid CRD YAML");
  const matches = documents.map(document => document.toJS({ maxAliasCount: 50 }) as unknown)
    .filter((value): value is ObjectValue => object(value) && value.kind === "CustomResourceDefinition"
      && object(value.spec) && object(value.spec.names) && value.spec.names.kind === kind);
  if (matches.length !== 1) throw new Error("expected one matching CRD");
  const crd = matches[0];
  if (!crd || crd.apiVersion !== "apiextensions.k8s.io/v1" || !object(crd.spec)) throw new Error("expected a v1 CRD");
  const spec = crd.spec;
  if (spec.scope !== "Namespaced" || typeof spec.group !== "string" || !object(spec.names)
    || typeof spec.names.plural !== "string" || !Array.isArray(spec.versions)) throw new Error("expected a namespaced CRD");
  const versions = spec.versions.filter((value): value is ObjectValue => object(value)
    && value.served === true && (version === undefined ? value.storage === true : value.name === version));
  const selected = versions[0];
  if (versions.length !== 1 || !selected || typeof selected.name !== "string"
    || !object(selected.schema) || !object(selected.schema.openAPIV3Schema)) throw new Error("expected one served CRD version");
  const schema = selected.schema.openAPIV3Schema;
  if (!object(schema.properties) || !object(schema.properties.spec)) throw new Error("CRD has no spec schema");
  schemaData(schema);
  const declaration = await compile(schema.properties.spec as JSONSchema, `${kind}Spec`, {
    bannerComment: "", additionalProperties: false, unknownAny: true,
    $refOptions: { resolve: { external: false } },
  });
  const descriptor = {
    apiVersion: `${spec.group}/${selected.name}`, kind,
    apiResource: { plural: spec.names.plural, scope: "Namespaced", schemaSha256: `sha256:${createHash("sha256").update(text).digest("hex")}` },
  };
  return `${HEADER}import { defineNamespacedResource } from "@reakt/kubernetes";\n\n${declaration}\nexport const ${kind} = defineNamespacedResource<${kind}Spec>(${JSON.stringify(descriptor, null, 2)});\n`;
}

async function fetchCrd(url: string): Promise<string> {
  const source = new URL(url);
  if (source.protocol !== "https:" || source.username || source.password) throw new Error("CRD URL must be HTTPS without credentials");
  const response = await fetch(source, { signal: AbortSignal.timeout(30_000), redirect: "error" });
  if (!response.ok || !response.body) throw new Error("CRD fetch failed");
  const chunks: Uint8Array[] = [];
  let size = 0;
  for await (const chunk of response.body) {
    size += chunk.byteLength;
    if (size > MAX_BYTES) throw new Error("CRD response exceeds size limit");
    chunks.push(chunk);
  }
  return new TextDecoder("utf-8", { fatal: true }).decode(Buffer.concat(chunks));
}

export async function fetchTypes(url: string, kind: string, output: string, version?: string): Promise<void> {
  const code = await generateCrdTypes(await fetchCrd(url), kind, version);
  const path = resolve(output);
  let exists = false;
  try {
    const previous = await readFile(path, "utf8");
    if (!previous.startsWith(HEADER)) throw new Error("refusing to overwrite a source file");
    exists = true;
  } catch (error) {
    if (!object(error) || error.code !== "ENOENT") throw error;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, code, { flag: exists ? "w" : "wx" });
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [url, kind, output, version, ...extra] = process.argv.slice(2);
  try {
    if (!url || !kind || !output || extra.length) throw new Error("expected URL KIND OUTPUT [VERSION]");
    await fetchTypes(url, kind, output, version);
    console.log(JSON.stringify({ output: resolve(output), kind, generated: true }));
  } catch {
    console.error("aps: CRD fetch or type generation failed");
    process.exitCode = 1;
  }
}
